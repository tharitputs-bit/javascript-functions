// Arrow Function
// บวก
let add = (a,b) => a+b;
console.log(`ผลบวกคือ ${add(10,5)}`);

//ลบ
let subtract = (a,b) => a-b;
console.log(`ผลลบคือ ${subtract(10,5)}`);

//คูณ
let multiply = (a,b) => a*b;
console.log(`ผลคูณคือ ${multiply(10,5)}`);

//หาร
let divide = (a,b) => a/b;
console.log(`ผลหารคือ ${divide(10,5)}`);

